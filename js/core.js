// ---------- RNG ----------
function mulberry32(a){return function(){a|=0;a=a+0x6D2B79F5|0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296}}
const R={
  rng:mulberry32((Date.now()^(Math.random()*1e9))>>>0),
  f(){return this.rng()},
  i(a,b){return a+Math.floor(this.rng()*(b-a+1))},
  pick(a){return a[Math.floor(this.rng()*a.length)]},
  chance(p){return this.rng()<p},
  shuffle(a){for(let i=a.length-1;i>0;i--){const j=Math.floor(this.rng()*(i+1));[a[i],a[j]]=[a[j],a[i]]}return a},
  weighted(list){let s=0;for(const e of list)s+=e.w;let r=this.rng()*s;for(const e of list){r-=e.w;if(r<=0)return e.v}return list[list.length-1].v}
};
