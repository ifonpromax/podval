const SPR={};
function S(name,rows,pal){
  for(const r of rows) if(r.length!==TS) console.warn('sprite',name,'bad row',r,r.length);
  SPR[name]={rows,pal:pal||{},c:null,wc:null};
}
function sprCanvas(name){
  const s=SPR[name]; if(!s) throw new Error('no sprite '+name);
  if(!s.c){
    const c=document.createElement('canvas'); c.width=TS; c.height=TS;
    const g=c.getContext('2d');
    s.rows.forEach((row,y)=>{for(let x=0;x<TS;x++){const ch=row[x]; if(ch==='.')continue; const col=s.pal[ch]||PAL[ch]; if(!col)continue; g.fillStyle=col; g.fillRect(x,y,1,1);}});
    s.c=c;
    const w=document.createElement('canvas'); w.width=TS; w.height=TS;
    const wg=w.getContext('2d'); wg.drawImage(c,0,0); wg.globalCompositeOperation='source-atop'; wg.fillStyle='#fff'; wg.fillRect(0,0,TS,TS);
    s.wc=w;
  }
  return s.c;
}
function sprWhite(name){sprCanvas(name);return SPR[name].wc}

